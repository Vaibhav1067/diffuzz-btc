#!/usr/bin/env bash
# Fetch the seed test vectors at pinned upstream commits and record their provenance.
#
# Output: vectors/core/*.json, vectors/bip341/wallet-test-vectors.json, vectors/SOURCES.md
# The run is deterministic: same pins => byte-identical files and SOURCES.md.
# Requires: bash, curl, sha256sum.
set -euo pipefail

# Bitcoin Core v32.1 (tag commit).
CORE_TAG="v32.1"
CORE_COMMIT="f0de87f040621468b956f01f526a43a010310501"
CORE_FILES=(script_tests.json tx_valid.json tx_invalid.json sighash.json)

# bitcoin/bips master as of 2026-11-13.
BIPS_COMMIT="b34d9f751791d4feb22feff4f2ed00bcac83961b"
BIP341_PATH="bip-0341/wallet-test-vectors.json"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/vectors"
SOURCES="$OUT/SOURCES.md"

mkdir -p "$OUT/core" "$OUT/bip341"

fetch() { # url dest
    local url="$1" dest="$2"
    echo "fetch $url" >&2
    curl --fail --silent --show-error --location --retry 3 --output "$dest.tmp" "$url"
    if [ ! -s "$dest.tmp" ]; then
        echo "error: empty download from $url" >&2
        rm -f "$dest.tmp"
        exit 1
    fi
    mv "$dest.tmp" "$dest"
}

sha() { sha256sum "$1" | cut -d' ' -f1; }

rows=""
row() { # relative-path url
    rows+="| \`$1\` | $2 | \`$(sha "$OUT/$1")\` |"$'\n'
}

for f in "${CORE_FILES[@]}"; do
    url="https://raw.githubusercontent.com/bitcoin/bitcoin/$CORE_COMMIT/src/test/data/$f"
    fetch "$url" "$OUT/core/$f"
    row "core/$f" "$url"
done

url="https://raw.githubusercontent.com/bitcoin/bips/$BIPS_COMMIT/$BIP341_PATH"
fetch "$url" "$OUT/bip341/wallet-test-vectors.json"
row "bip341/wallet-test-vectors.json" "$url"

cat > "$SOURCES" <<EOF
# Vector sources

Generated by \`scripts/fetch_vectors.sh\`. Do not edit by hand; change the pins in the script and re-run.

| Upstream | Ref | Commit |
|---|---|---|
| [bitcoin/bitcoin](https://github.com/bitcoin/bitcoin) | \`$CORE_TAG\` | \`$CORE_COMMIT\` |
| [bitcoin/bips](https://github.com/bitcoin/bips) | \`master\` | \`$BIPS_COMMIT\` |

Bitcoin Core's vectors are MIT-licensed; BIP-341 is BSD-3-Clause. Files are stored unmodified.

| File | Source URL | SHA-256 |
|---|---|---|
$rows
EOF

echo "wrote $SOURCES" >&2
